#!/usr/bin/env python3
"""Run baseline PCA, Harmony or Scanorama on a frozen benchmark input."""

from __future__ import annotations

import argparse
import hashlib
import inspect
import json
import time
from pathlib import Path

import numpy as np

from benchmark_common import (
    BATCH_KEY,
    SEED,
    load_benchmark,
    obs_names_sha256,
    save_embedding,
    set_seed,
)


def file_hash(path: Path, block_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(block_size):
            digest.update(block)
    return digest.hexdigest()


def load_pca_sidecar(adata, path: Path | None, metadata_path: Path | None):
    if path is None:
        embedding = np.asarray(adata.obsm["X_pca"], dtype=np.float32)
        return embedding, {
            "pca_source": "legacy_h5ad_obsm_X_pca",
            "pca_file": None,
            "pca_sha256": None,
            "pca_metadata": None,
        }
    if metadata_path is None:
        raise RuntimeError("--pca-metadata is required with --pca-file")
    metadata = json.loads(metadata_path.read_text())
    expected_hash = obs_names_sha256(adata.obs_names)
    if metadata.get("status") != "completed":
        raise RuntimeError("PCA sidecar metadata is not completed")
    if metadata.get("backend") != "OmicVerse ov.pp.pca":
        raise RuntimeError("PCA sidecar was not generated by OmicVerse")
    if metadata.get("omicverse_global_mode") != "cpu-gpu-mixed":
        raise RuntimeError("PCA sidecar did not use OmicVerse CPU/GPU mixed mode")
    if metadata.get("obs_names_sha256") != expected_hash:
        raise RuntimeError("PCA sidecar cell hash does not match the input H5AD")
    embedding = np.load(path, mmap_mode="r")
    if embedding.shape != (adata.n_obs, 30):
        raise RuntimeError(f"Unexpected PCA sidecar shape: {embedding.shape}")
    if not np.isfinite(embedding).all():
        raise RuntimeError("PCA sidecar contains non-finite values")
    actual_hash = file_hash(path)
    expected_file_hash = metadata.get("artifacts", {}).get("pca_sha256")
    if actual_hash != expected_file_hash:
        raise RuntimeError("PCA sidecar file hash does not match its metadata")
    return np.asarray(embedding, dtype=np.float32), {
        "pca_source": "omicverse_sidecar",
        "pca_file": str(path.resolve()),
        "pca_sha256": actual_hash,
        "pca_metadata": str(metadata_path.resolve()),
        "pca_metadata_sha256": file_hash(metadata_path),
    }


def run_harmony(
    adata,
    pca: np.ndarray,
    theta: float,
    device: str,
    max_iter: int,
    backend: str,
) -> np.ndarray:
    if backend == "harmonypy":
        import harmonypy as hm

        result = hm.run_harmony(
            pca,
            adata.obs,
            vars_use=BATCH_KEY,
            theta=theta,
            max_iter_harmony=max_iter,
            random_state=SEED,
            device=device,
            verbose=True,
        )
        return np.asarray(result.Z_corr, dtype=np.float32)

    import omicverse as ov
    from omicverse.external.harmony import run_harmony as ov_run_harmony

    if device == "cuda":
        ov.settings.cpu_gpu_mixed_init()
    else:
        ov.settings.cpu_init()
    parameters = inspect.signature(ov_run_harmony).parameters
    kwargs = {
        "theta": theta,
        "max_iter_harmony": max_iter,
        "random_state": SEED,
        "verbose": True,
    }
    if "device" in parameters:
        kwargs["device"] = device
    if "use_gpu" in parameters:
        kwargs["use_gpu"] = device == "cuda"
    result = ov_run_harmony(
        pca,
        adata.obs,
        BATCH_KEY,
        **kwargs,
    )
    return np.asarray(result.result(), dtype=np.float32)


def run_scanorama(adata, dimred: int) -> np.ndarray:
    import scanorama

    batch_values = adata.obs[BATCH_KEY].astype(str).to_numpy()
    batches = sorted(set(batch_values))
    pieces = []
    positions = []
    for batch in batches:
        pos = np.flatnonzero(batch_values == batch)
        piece = adata[pos].copy()
        piece.obs_names_make_unique()
        pieces.append(piece)
        positions.append(pos)
    scanorama.integrate_scanpy(pieces, dimred=dimred, seed=SEED)
    result = np.zeros((adata.n_obs, dimred), dtype=np.float32)
    for piece, pos in zip(pieces, positions):
        embedding = np.asarray(piece.obsm["X_scanorama"], dtype=np.float32)
        result[pos, : embedding.shape[1]] = embedding
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--method", required=True, choices=["pca", "harmony", "scanorama"])
    parser.add_argument("--theta", type=float, default=2.0)
    parser.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    parser.add_argument(
        "--harmony-backend",
        choices=["harmonypy", "omicverse"],
        default="harmonypy",
    )
    parser.add_argument("--max-iter", type=int, default=20)
    parser.add_argument("--dimred", type=int, default=30)
    parser.add_argument("--config-id")
    parser.add_argument("--pca-file", type=Path)
    parser.add_argument("--pca-metadata", type=Path)
    args = parser.parse_args()
    set_seed()
    started = time.time()
    adata = load_benchmark(args.input)
    pca, pca_record = load_pca_sidecar(adata, args.pca_file, args.pca_metadata)
    if args.method == "pca":
        embedding = pca
        params = {
            "n_components": int(embedding.shape[1]),
            "correction": "none",
            **pca_record,
        }
        config_id = args.config_id or "baseline"
        packages = []
    elif args.method == "harmony":
        embedding = run_harmony(
            adata,
            pca,
            args.theta,
            args.device,
            args.max_iter,
            args.harmony_backend,
        )
        params = {
            "theta": args.theta,
            "device": args.device,
            "backend": args.harmony_backend,
            "omicverse_global_mode": (
                "cpu-gpu-mixed"
                if args.harmony_backend == "omicverse" and args.device == "cuda"
                else None
            ),
            "max_iter_harmony": args.max_iter,
            "input": "X_pca",
            **pca_record,
        }
        config_id = args.config_id or f"theta{args.theta:g}"
        packages = (
            ["omicverse", "torch"]
            if args.harmony_backend == "omicverse"
            else ["harmonypy", "torch"]
        )
    else:
        embedding = run_scanorama(adata, args.dimred)
        params = {"dimred": args.dimred, "batch_unit": BATCH_KEY}
        config_id = args.config_id or f"dim{args.dimred}"
        packages = ["scanorama"]
    save_embedding(
        embedding,
        adata,
        args.output_dir,
        args.method,
        config_id,
        params,
        started,
        packages,
    )


if __name__ == "__main__":
    main()
